import { Share } from 'react-native';
import {
  BisectionIteration,
  FixedPointIteration,
  NewtonIteration,
  RootFindingResult,
  SecantIteration,
} from '../types/rootFinding';
import { InterpolationResult } from '../types/interpolation';
import { formatFloat } from '../math/evaluator';

export function formatRootResultAsMarkdown(result: RootFindingResult): string {
  const rootStr = result.root !== null ? formatFloat(result.root, 6) : 'N/A';
  let md = `### Calculix Solution: ${result.method.toUpperCase()}\n\n`;
  md += `**Equation:** \`f(x) = ${result.parsedFunction}\`  \n`;
  if (result.parsedDerivative) {
    md += `**Derivative:** \`f'(x) = ${result.parsedDerivative}\`  \n`;
  }
  md += `**Root Estimate:** \`x* = ${rootStr}\`  \n`;
  md += `**Status:** ${result.status} (${result.totalIterations} steps, ${result.executionTimeMs} ms)  \n\n`;

  if (result.iterations.length > 0) {
    if (result.method === 'bisection') {
      md += `| Step | a | b | Midpoint | f(mid) | Rel. Error (%) |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- | :--- |\n`;
      result.iterations.forEach((iter) => {
        const it = iter as BisectionIteration;
        md += `| ${it.iteration} | ${formatFloat(it.a, 6)} | ${formatFloat(it.b, 6)} | ${formatFloat(it.x_n, 6)} | ${formatFloat(it.f_xn, 6)} | ${formatFloat(it.relError, 4)} |\n`;
      });
    } else if (result.method === 'newton') {
      md += `| Step | xₙ | f(xₙ) | f'(xₙ) | xₙ₊₁ | Rel. Error (%) |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- | :--- |\n`;
      result.iterations.forEach((iter) => {
        const it = iter as NewtonIteration;
        md += `| ${it.iteration} | ${formatFloat(it.x_n, 6)} | ${formatFloat(it.f_xn, 6)} | ${formatFloat(it.f_prime_xn, 6)} | ${formatFloat(it.x_next, 6)} | ${formatFloat(it.relError, 4)} |\n`;
      });
    } else if (result.method === 'secant') {
      md += `| Step | xₙ | f(xₙ) | xₙ₊₁ | Rel. Error (%) |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- |\n`;
      result.iterations.forEach((iter) => {
        const it = iter as SecantIteration;
        md += `| ${it.iteration} | ${formatFloat(it.x_n, 6)} | ${formatFloat(it.f_xn, 6)} | ${formatFloat(it.x_next, 6)} | ${formatFloat(it.relError, 4)} |\n`;
      });
    } else {
      md += `| Step | xₙ | g(xₙ) | f(xₙ) | Rel. Error (%) |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- |\n`;
      result.iterations.forEach((iter) => {
        const it = iter as FixedPointIteration;
        md += `| ${it.iteration} | ${formatFloat(it.x_n, 6)} | ${formatFloat(it.g_xn, 6)} | ${formatFloat(it.f_xn, 6)} | ${formatFloat(it.relError, 4)} |\n`;
      });
    }
  }

  return md;
}

export function formatRootResultAsLatex(result: RootFindingResult): string {
  const rootStr = result.root !== null ? formatFloat(result.root, 6) : 'N/A';
  let tex = `% Solution generated by Calculix\n`;
  tex += `\\begin{table}[htbp]\n`;
  tex += `\\centering\n`;
  tex += `\\caption{Convergence Table for $f(x) = ${result.parsedFunction}$ using ${result.method}}\n`;

  if (result.method === 'bisection') {
    tex += `\\begin{tabular}{cccccc}\n`;
    tex += `\\hline\n`;
    tex += `Iteration & a & b & Midpoint & f(mid) & Rel. Error (\\%) \\\\\n`;
    tex += `\\hline\n`;
    result.iterations.forEach((iter) => {
      const it = iter as BisectionIteration;
      tex += `${it.iteration} & ${formatFloat(it.a, 6)} & ${formatFloat(it.b, 6)} & ${formatFloat(it.x_n, 6)} & ${formatFloat(it.f_xn, 6)} & ${formatFloat(it.relError, 4)} \\\\\n`;
    });
  } else if (result.method === 'newton') {
    tex += `\\begin{tabular}{cccccc}\n`;
    tex += `\\hline\n`;
    tex += `Iteration & $x_n$ & $f(x_n)$ & $f'(x_n)$ & $x_{n+1}$ & Rel. Error (\\%) \\\\\n`;
    tex += `\\hline\n`;
    result.iterations.forEach((iter) => {
      const it = iter as NewtonIteration;
      tex += `${it.iteration} & ${formatFloat(it.x_n, 6)} & ${formatFloat(it.f_xn, 6)} & ${formatFloat(it.f_prime_xn, 6)} & ${formatFloat(it.x_next, 6)} & ${formatFloat(it.relError, 4)} \\\\\n`;
    });
  } else if (result.method === 'secant') {
    tex += `\\begin{tabular}{ccccc}\n`;
    tex += `\\hline\n`;
    tex += `Iteration & $x_n$ & $f(x_n)$ & $x_{n+1}$ & Rel. Error (\\%) \\\\\n`;
    tex += `\\hline\n`;
    result.iterations.forEach((iter) => {
      const it = iter as SecantIteration;
      tex += `${it.iteration} & ${formatFloat(it.x_n, 6)} & ${formatFloat(it.f_xn, 6)} & ${formatFloat(it.x_next, 6)} & ${formatFloat(it.relError, 4)} \\\\\n`;
    });
  } else {
    tex += `\\begin{tabular}{ccccc}\n`;
    tex += `\\hline\n`;
    tex += `Iteration & $x_n$ & $g(x_n)$ & $f(x_n)$ & Rel. Error (\\%) \\\\\n`;
    tex += `\\hline\n`;
    result.iterations.forEach((iter) => {
      const it = iter as FixedPointIteration;
      tex += `${it.iteration} & ${formatFloat(it.x_n, 6)} & ${formatFloat(it.g_xn, 6)} & ${formatFloat(it.f_xn, 6)} & ${formatFloat(it.relError, 4)} \\\\\n`;
    });
  }

  tex += `\\hline\n`;
  tex += `\\end{tabular}\n`;
  tex += `\\label{tab:calculix-${result.method}}\n`;
  tex += `\\end{table}\n\n`;
  tex += `% Computed root: x* = ${rootStr} in ${result.totalIterations} iterations.\n`;

  return tex;
}

export function formatInterpolationResultAsMarkdown(result: InterpolationResult): string {
  let md = `### Calculix Solution: ${result.method.toUpperCase()}\n\n`;
  md += `**Target Coordinate:** \`x* = ${result.targetX}\`  \n`;
  md += `**Interpolated Value:** \`P(${result.targetX}) = ${formatFloat(result.interpolatedY, 6)}\`  \n`;
  md += `**Polynomial:** \`${result.polynomialString}\`  \n\n`;

  if (result.method === 'newton-divided' && result.newtonTable) {
    md += `#### Divided Difference Matrix\n\n`;
    const headers = result.newtonTable.headers.join(' | ');
    const sep = result.newtonTable.headers.map(() => ':---').join(' | ');
    md += `| ${headers} |\n| ${sep} |\n`;
    result.newtonTable.matrix.forEach((row: number[]) => {
      const vals = row
        .map((v: number) => (Number.isFinite(v) ? formatFloat(v, 4) : '-'))
        .join(' | ');
      md += `| ${vals} |\n`;
    });
  }

  return md;
}

export async function shareSolutionText(title: string, content: string): Promise<void> {
  try {
    await Share.share({
      title,
      message: content,
    });
  } catch {
    // User cancelled or share dismissed
  }
}
